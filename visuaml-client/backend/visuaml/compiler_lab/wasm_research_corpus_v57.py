"""Deterministic, reusable canonical original-WASM corpus for v57+.

This is program DATA, not trained interpreter weights. Source bytes are
regenerated by the v51 canonical encoder and validated with Wasmtime.
"""
from __future__ import annotations

import random

from .wasm_control_flow_v51 import ControlOperation, ControlProgram


def op(name: str, imm: int | None = None) -> ControlOperation:
    return ControlOperation(name, imm)


def countdown() -> ControlProgram:
    return ControlProgram(1, (
        op("block"), op("loop"), op("local.get", 0),
        op("i32.eqz"), op("br_if", 1),
        op("local.get", 1), op("local.get", 0), op("i32.add"),
        op("local.set", 1), op("local.get", 0),
        op("i32.const", 1), op("i32.sub"),
        op("local.set", 0), op("br", 0),
        op("end"), op("end"), op("local.get", 1), op("end"),
    ))


def ifelse() -> ControlProgram:
    return ControlProgram(1, (
        op("local.get", 0), op("i32.const", 0),
        op("i32.lt_s"), op("if"),
        op("i32.const", 11), op("local.set", 1),
        op("else"), op("i32.const", 22),
        op("local.set", 1), op("end"),
        op("local.get", 1), op("end"),
    ))


def gcd12() -> ControlProgram:
    return ControlProgram(1, (
        op("local.get", 0), op("i32.eqz"),
        op("if"), op("i32.const", 12), op("return"), op("end"),
        op("local.get", 0), op("i32.const", 0), op("i32.lt_s"),
        op("if"), op("i32.const", 0), op("return"), op("end"),
        op("i32.const", 12), op("local.set", 1),
        op("block"), op("loop"),
        op("local.get", 0), op("local.get", 1),
        op("i32.sub"), op("i32.eqz"), op("br_if", 1),
        op("local.get", 0), op("local.get", 1), op("i32.gt_s"),
        op("if"),
        op("local.get", 0), op("local.get", 1),
        op("i32.sub"), op("local.set", 0),
        op("else"),
        op("local.get", 1), op("local.get", 0),
        op("i32.sub"), op("local.set", 1),
        op("end"), op("br", 0),
        op("end"), op("end"), op("local.get", 0), op("end"),
    ))


def generated(seed: int) -> ControlProgram:
    """New composition of four full-i32 operations, with local dependencies."""
    if type(seed) is not int or not 0 <= seed < 1024:
        raise ValueError("Seed outside bounded reproducibility domain")
    rng = random.Random(560000 + seed)
    ops = ("i32.add", "i32.sub", "i32.mul", "i32.lt_s", "i32.gt_s")
    operations = [op("local.get", 0)]
    for step in range(4):
        imm = rng.choice((
            -(1 << 31), -65537, -3, -1, 0, 1, 5, 4097,
            (1 << 31) - 1,
        ))
        operations.extend((
            op("i32.const", imm),
            op(ops[(seed + 2 * step) % len(ops)]),
        ))
        if (seed + step) % 3 == 0:
            operations.append(op("i32.eqz"))
        if step == 1:
            operations.append(op("local.tee", 1))
        if step == 2:
            operations.extend((
                op("local.get", 1), op(ops[(seed + 1) % len(ops)]),
            ))
    operations.append(op("end"))
    return ControlProgram(1, tuple(operations))


def corpus() -> dict[str, tuple[ControlProgram, tuple[int, ...]]]:
    cases = {
        "countdown": (countdown(), tuple(range(10))),
        "ifelse": (ifelse(), (-7, -1, 0, 1, 7)),
        "gcd12": (gcd12(), (-1, 0, 1, 2, 3, 5, 7, 9, 12, 17, 24)),
    }
    adversarial = (-(1 << 31), -17, -1, 0, 1, 19, (1 << 31) - 1)
    for seed in range(16):
        cases[f"generated_{seed:02d}"] = (generated(seed), adversarial)
    return cases
