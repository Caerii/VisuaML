import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_CORE ?? 'playwright-core');
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  await page.goto('http://localhost:4180/replay-viewer.html');
  await page.getByText(/First difference after PC 160/).waitFor();
  await page.getByRole('button', { name: 'Open Pocket checkpoint' }).click();
  await page.getByText(/call depth 1/).waitFor();
  await page.locator('#file').setInputFiles('release/examples/terrain-comparison.json');
  await page.getByText(/First difference after PC 160/).waitFor();
  await page.route('**/api/compiler-counterexample', route => route.abort());
  await page.getByRole('button', { name: 'Search terrain inputs' }).click();
  await page.getByText(/Saved search.*PC 100.*\[256\] → \[0\]/).waitFor();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download replayable counterexample' }).click();
  assert.equal((await downloaded).suggestedFilename(), 'terrain-counterexample.json');
  await page.getByRole('button', { name: 'Open two-call failure' }).click();
  await page.getByText('First difference at event 2 · result 6 → result 8').waitFor();
  assert.match(await page.locator('#detail').innerText(), /call beta 6 1 \. → call beta 8 1/);
  const failure = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download two-call failure' }).click();
  assert.equal((await failure).suggestedFilename(), 'two-call-failure.json');
  await page.locator('#file').setInputFiles('evidence/two-call-controller/failure.json');
  await page.getByText('First difference at event 2 · result 6 → result 8').waitFor();
  await page.getByRole('button', { name: 'Open tool choice intervention' }).click();
  await page.getByText('Feedback intervention at event 2 · result 10 → result 14').waitFor();
  assert.match(await page.locator('#detail').innerText(), /call beta 10 5 \. → call gamma 14 5/);
  const intervention = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download tool choice replay' }).click();
  assert.equal((await intervention).suggestedFilename(), 'composed-inference.json');
  await page.locator('#file').setInputFiles('evidence/composed-inference/replay.json');
  await page.getByText('Feedback intervention at event 2 · result 10 → result 14').waitFor();
  await page.getByRole('button', { name: 'Open tool acquisition replay' }).click();
  const acquisition = page.getByText('First intervention difference at event 2');
  await acquisition.waitFor();
  assert.match(await page.locator('#detail').innerText(), /substitution · event 3 · tool_selection/);
  const acquisitionDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download tool acquisition replay' }).click();
  assert.equal((await acquisitionDownload).suggestedFilename(), 'tool-acquisition.json');
  await page.locator('#file').setInputFiles('evidence/tool-acquisition/replay.json');
  await acquisition.waitFor();
  await page.getByRole('button', { name: 'Open causal assembly replay' }).click();
  const causal = page.getByText('5 cases · 73 compared source boundaries');
  await causal.waitFor();
  assert.match(await page.locator('#detail').innerText(), /M\[1\] = 0xfffffffe/);
  const causalDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download causal assembly replay' }).click();
  assert.equal((await causalDownload).suggestedFilename(), 'causal-tensor-assembly.json');
  await page.locator('#file').setInputFiles('evidence/causal-tensor-assembly/replay.json');
  await causal.waitFor();
  await page.getByRole('button', { name: 'Open paired routing replay' }).click();
  const paired = page.getByText('Feedback 10 → 12 switched the second handle');
  await paired.waitFor();
  assert.match(await page.locator('#detail').innerText(), /handle 70\(10, 2\) → 16 · handle 860\(12, 2\) → 8/);
  const pairedDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download paired routing replay' }).click();
  assert.equal((await pairedDownload).suggestedFilename(), 'paired-routing.json');
  await page.locator('#file').setInputFiles('evidence/paired-routing/replay.json');
  await paired.waitFor();
  await page.getByRole('button', { name: 'Open vocabulary-token replay' }).click();
  const tokenCommit = page.getByText('Store commits at emitted token 84');
  await tokenCommit.waitFor();
  assert.match(await page.locator('#detail').innerText(), /0xfffffffe.*0xffffffff/);
  const tokenDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download vocabulary-token replay' }).click();
  assert.equal((await tokenDownload).suggestedFilename(), 'vocabulary-tensor-assembly.json');
  await page.locator('#file').setInputFiles('evidence/vocabulary-tensor-assembly/replay.json');
  await tokenCommit.waitFor();
  await page.getByRole('button', { name: 'Open decoder execution replay' }).click();
  const executionCommit = page.getByText('Generated store commits at token 24');
  await executionCommit.waitFor();
  assert.match(await page.locator('#detail').innerText(), /Branch chooses PC 8 → 6/);
  const executionDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download decoder execution replay' }).click();
  assert.equal((await executionDownload).suggestedFilename(), 'decoder-execution-loop.json');
  await page.locator('#file').setInputFiles('evidence/decoder-execution-loop/replay.json');
  await executionCommit.waitFor();
  await page.getByRole('button', { name: 'Open word decoder replay' }).click();
  const wordCountdown = page.getByText('One payload byte changes countdown from 13 to 9 instructions');
  await wordCountdown.waitFor();
  assert.match(await page.locator('#detail').innerText(), /Next branch PC: 0 → 4/);
  const wordDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download word decoder replay' }).click();
  assert.equal((await wordDownload).suggestedFilename(), 'word-decoder.json');
  await page.locator('#file').setInputFiles('evidence/word-decoder/replay.json');
  await wordCountdown.waitFor();
  await page.getByRole('button', { name: 'Open rolling context replay' }).click();
  const rolling = page.getByText('6,228 generated tokens · 504 peak active');
  await rolling.waitFor();
  assert.match(await page.locator('#detail').innerText(), /Missing counter: load 3 recovered 0 instead of 64/);
  const rollingDownload = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download rolling context replay' }).click();
  assert.equal((await rollingDownload).suggestedFilename(), 'rolling-context.json');
  await page.locator('#file').setInputFiles('evidence/rolling-context/replay.json');
  await rolling.waitFor();
} finally { await browser.close(); }
