import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_CORE ?? 'playwright-core');
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] });
try {
  const page = await browser.newPage();
  await page.goto('http://localhost:4180/replay-viewer.html');
  await page.getByText(/First difference after PC 160/).waitFor();
  await page.getByRole('button', { name: 'Open Pocket checkpoint' }).click();
  await page.getByText(/call depth 1/).waitFor();
  await page.locator('#file').setInputFiles('release/examples/terrain-comparison.json');
  await page.getByText(/First difference after PC 160/).waitFor();
  await page.route('**/api/compiler-counterexample', route => route.abort());
  await page.getByRole('button', { name: 'Search terrain inputs' }).click();
  await page.getByText(/Saved search.*PC 100.*\[256\] → \[0\]/).waitFor();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download replayable counterexample' }).click();
  assert.equal((await downloaded).suggestedFilename(), 'terrain-counterexample.json');
  await page.getByRole('button', { name: 'Open two-call failure' }).click();
  await page.getByText('First difference at event 2 · result 6 → result 8').waitFor();
  assert.match(await page.locator('#detail').innerText(), /call beta 6 1 \. → call beta 8 1/);
  const failure = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download two-call failure' }).click();
  assert.equal((await failure).suggestedFilename(), 'two-call-failure.json');
  await page.locator('#file').setInputFiles('evidence/two-call-controller/failure.json');
  await page.getByText('First difference at event 2 · result 6 → result 8').waitFor();
  await page.getByRole('button', { name: 'Open tool choice intervention' }).click();
  await page.getByText('Feedback intervention at event 2 · result 10 → result 14').waitFor();
  assert.match(await page.locator('#detail').innerText(), /call beta 10 5 \. → call gamma 14 5/);
  const intervention = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Download tool choice replay' }).click();
  assert.equal((await intervention).suggestedFilename(), 'composed-inference.json');
  await page.locator('#file').setInputFiles('evidence/composed-inference/replay.json');
  await page.getByText('Feedback intervention at event 2 · result 10 → result 14').waitFor();
} finally { await browser.close(); }
